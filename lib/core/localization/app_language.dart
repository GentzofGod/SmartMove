  static String tr(WidgetRef ref, String key) {
    final currentLanguage = ref.watch(appLanguageProvider);
    return get(key, currentLanguage);
  }

  static String get(String key, String languageName) {
    final langMap = _translations[languageName] ?? _translations['English']!;
    return langMap[key] ?? _translations['English']![key] ?? key;
  }

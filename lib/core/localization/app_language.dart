class NigerianLanguage {
  final String code;
  final String name;
  final String nativeName;
  final String region;

  const NigerianLanguage({
    required this.code,
    required this.name,
    required this.nativeName,
    required this.region,
  });
}

class AppLanguageNotifier extends Notifier<String> {
  @override
  String build() {
    _loadSavedLanguage();
    return 'English';
  }

  Future<void> _loadSavedLanguage() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final saved = prefs.getString('smartmove_app_language');
      if (saved != null && saved.isNotEmpty) {
        state = saved;
      }
    } catch (_) {}
  }

  Future<void> setLanguage(String languageName) async {
    state = languageName;
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString('smartmove_app_language', languageName);
    } catch (_) {}
  }
}

final appLanguageProvider = NotifierProvider<AppLanguageNotifier, String>(() {
  return AppLanguageNotifier();
});

